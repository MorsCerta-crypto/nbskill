def numbered_notebook_path(nbs_path, name, index=None):
    "Return a flat numbered notebook path for a simple module name."
    root = Path(nbs_path)
    name = Path(name).stem
    if not re.fullmatch(r"[A-Za-z_]\w*", name): raise ValueError("name must be a simple Python module name")
    if index is None:
        numbers = [int(path.name.split("_", 1)[0]) for path in root.glob("[0-9][0-9]_*.ipynb")]
        index = max(numbers, default=-1) + 1
    return root / f"{index:02d}_{name}.ipynb"


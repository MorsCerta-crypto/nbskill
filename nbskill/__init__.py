"""Context search, structural review, and nbdev craft for AI coding agents

`nbskill` helps AI coding agents understand nbdev notebooks quickly and write notebooks that humans actually enjoy reading. It works standalone as a Python library and Pyskill, and pairs cleanly with `aai-coding`.

Notebooks shine as a tool for human understanding when each chapter pairs concise explanations with clean code, visible examples, and direct assertions. `nbskill` makes that style easy for agents by giving them focused context retrieval, honest structural and narrative checks (including catching `#| hide` walls and broken cell state), noise-free diffs, and standalone atomic editing and execution.

Install `nbskill` from its GitHub release tag in the agent's Python environment:

```toml
[project]
dependencies = ["nbskill==0.0.23"]

[tool.uv.sources]
nbskill = { git = "https://github.com/MorsCerta-crypto/nbskill.git", tag = "0.0.23" }
```

`nbskill` registers `nbskill.skill` in the `pyskills` entry-point group. Load it in Python with `from nbskill.skill import *` and read `doc(nbskill.skill)` for the complete workflow. For external agents using `SKILL.md`, run `install_nbskill`.

| Function | Purpose |
|---|---|
| `nb_arch(path=".")` | Compact architecture overview: dependency layers, God-Hubs, communities, and inversions |
| `nb_graph(path=".")` | Deterministic hybrid graph across notebooks and handwritten `.py` (`.to_mermaid()`, `.to_json()`) |
| `impact(target, scope=".")` | Transitive blast radius across notebooks, handwritten `.py`, and `tests/` with minimal test commands |
| `trace_path(src, dst, scope=".")` | Shortest dependency or call chain between two modules or symbols |
| `nb_map(path=".")` | Map notebooks, H2 chapters, exported symbols, and hidden-cell ratios |
| `generated_owner(py_path)` | Route an `# AUTOGENERATED!` module back to its `.ipynb` source |
| `chapter_context(path, chapter)` | Read one H2 chapter with cell IDs, hashes, and freshness |
| `symbol_context(target, scope=".")` | Bundle a symbol's explanation, definition, `@patch` API, callees, resolved callers, and state |
| `search_nb(pattern, path=".")` | Smart-case regex search across notebook cells |
| `review_nb(path=".")` / `check_nb(path=".")` | Structural, state, narrative, architecture, and `chkstyle` diagnostics |
| `diff_nb(path, ref_a="HEAD")` | Cell-level diff across code and Markdown without JSON or output noise |
| `notebook_state(path)` | Clean, dirty, stale, error, and unknown execution state per cell |
| `edit_nb(path, ops)` | Atomic cell edits with strict text-match and hash checks |
| `exec_nb(path, chapter=...)` | Focused execution from top through a chapter or cell ID |

- `00_core.ipynb`: cell directives, multi-target exports, AST definitions/imports, H2 chapters, and `generated_owner`.
- `01_state.ipynb`: execution freshness, downstream staleness, and `diff_nb`.
- `02_graph.ipynb`: hybrid `ProjectGraph`, `nb_arch`, `impact`, and `trace_path`.
- `03_context.ipynb`: `nb_map`, `chapter_context`, graph-backed `symbol_context`, and `search_nb`.
- `04_review.ipynb`: structural, state, narrative, architecture, hide-balance, and `chkstyle` diagnostics.
- `05_work.ipynb`: standalone `edit_nb`, `exec_nb`, and `install_skill`.
- `06_skill.ipynb`: `nbskill.skill` Pyskill entry point and authoring contract.

Modules:

- `nbskill.skill`: Use `nbskill.skill` for nbdev notebooks and generated `.py` modules (`from nbskill.skill import *`). Standalone or beside `aai-coding`: `nbskill.skill` for project architecture, blast radius, dependency paths, symbol/chapter bundles, structural and architectural review, clean diffs, and freshness; `exhash`, `rgapi`, and `nbdev-test` for edits, fast grep, and full test runs."""

